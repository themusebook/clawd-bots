#!/usr/bin/env python3
"""Generate companion-core/mascot-data.ts from the iOS mascot sources.

The iOS tables are themselves generated from the Blob Studio export and are
marked do-not-hand-edit; the same rule applies here — this script is the
source of truth bridge. It reads:
  - ClawdAvatar.swift  -> the silhouette path, baked into face-box
    coordinates with the desktop's exact transforms, plus its bounds.
  - ClawdFaceData.swift -> expressionsFlat / gazeFlat / mouthsFlat / pools.

Re-run after either Swift file changes; the output is checked by
mascot.test.ts shape assertions (counts per table).
"""
import json
import re
import sys
from pathlib import Path

REF = Path.home() / "workspace/clawdmobile-android/ios-reference"
OUT = Path.home() / "workspace/clawdmobile-android/clawdmobile/companion-core/mascot-data.ts"

avatar = (REF / "ClawdAvatar.swift").read_text()
facedata = (REF / "ClawdFaceData.swift").read_text()


def extract_string(swift: str, marker: str) -> str:
    start = swift.index(marker) + len(marker)
    open_q = swift.index('"""', start)
    close_q = swift.index('"""', open_q + 3)
    return swift[open_q + 3 : close_q].strip()


def extract_array(swift: str, name: str) -> list:
    start = swift.index(f"static let {name}")
    open_b = swift.index("= [", start) + 2
    close_b = swift.index("]", open_b)
    body = swift[open_b + 1 : close_b]
    return [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", body)]


def fmt_num(x: float) -> str:
    if x == int(x) and abs(x) < 1e15:
        return str(int(x))
    return repr(round(x, 6))


# --- Silhouette: parse M/C/Z token stream, apply the face-box transform ---
# Desktop artwork -> face box: translate(210,80), then scale(0.593899),
# then translate(-56.5564,-37.6751)  (CGAffineTransform concatenation order).
S = 0.593899


def tx(x: float, y: float) -> tuple[float, float]:
    return ((x + 210) * S - 56.5564, (y + 80) * S - 37.6751)


raw_path = extract_string(avatar, "static let path =")
tokens = re.findall(r"[MCZ]|-?\d+(?:\.\d+)?", raw_path)
out_parts: list[str] = []
points: list[tuple[float, float]] = []
i = 0
while i < len(tokens):
    cmd = tokens[i]
    if cmd == "Z":
        out_parts.append("Z")
        i += 1
    elif cmd == "M":
        x, y = float(tokens[i + 1]), float(tokens[i + 2])
        px, py = tx(x, y)
        points.append((px, py))
        out_parts.append(f"M{fmt_num(px)} {fmt_num(py)}")
        i += 3
    elif cmd == "C":
        nums = [float(tokens[i + j]) for j in range(1, 7)]
        baked = []
        for j in range(0, 6, 2):
            px, py = tx(nums[j], nums[j + 1])
            points.append((px, py))
            baked.append(f"{fmt_num(px)} {fmt_num(py)}")
        out_parts.append("C" + " ".join(baked))
        i += 7
    else:
        sys.exit(f"unexpected token {cmd!r} at {i}")
silhouette = " ".join(out_parts)
xs = [p[0] for p in points]
ys = [p[1] for p in points]
# Control-hull bounds: an over-estimate of the true bezier bounds, used only
# for the gradient direction — the Swift gradient uses the true bounds, and
# the hull differs by a hair at this scale. Sampled bounds would be tighter;
# the hull is honest and stable.
bounds = {"minX": min(xs), "minY": min(ys), "maxX": max(xs), "maxY": max(ys)}

# --- Face tables ---
expressions = extract_array(facedata, "expressionsFlat")
gaze = extract_array(facedata, "gazeFlat")
mouths = extract_array(facedata, "mouthsFlat")
assert len(expressions) == 25 * 2 * 48 * 2, len(expressions)
assert len(gaze) == 25 * 2, len(gaze)
assert len(mouths) == 25 * 4, len(mouths)

pools_block = facedata[facedata.index("static let pools") :]
pools_block = pools_block[: pools_block.index("static let expressionCadence")]
pools: dict[str, list[int]] = {}
for m in re.finditer(r"\.(\w+): \[([\d, ]+)\]", pools_block):
    pools[m.group(1)] = [int(x) for x in m.group(2).split(",") if x.strip()]

states_block = facedata[facedata.index("enum ClawdState") :]
states_block = states_block[: states_block.index("struct ClawdBodyMotion")]
states: list[str] = re.findall(r'case \w+ = "([^"]+)"', states_block)
assert len(states) == 40, len(states)


def num_array(name: str, values: list, per_line: int = 12) -> str:
    lines = []
    for j in range(0, len(values), per_line):
        lines.append("  " + ", ".join(fmt_num(v) for v in values[j : j + per_line]) + ",")
    return f"export const {name}: number[] = [\n" + "\n".join(lines) + "\n]\n"


header = """/**
 * GENERATED by scripts/generate-mascot-data.py from the iOS mascot sources
 * (App/ClawdAvatar.swift + App/ClawdFaceData.swift, themselves generated
 * from the Blob Studio export — the same tables the desktop ships).
 * Do not hand-edit; re-run the generator. Same numbers as the desktop,
 * which is the whole point.
 */
"""

body = header
body += num_array("EXPRESSIONS_FLAT", expressions)
body += num_array("GAZE_FLAT", gaze)
body += num_array("MOUTHS_FLAT", mouths)
body += "export const POOLS: Record<string, number[]> = {\n"
for state in states:
    if state in pools:
        body += f"  {json.dumps(state)}: [{', '.join(str(v) for v in pools[state])}],\n"
body += "}\n\n"
body += "export const CLAWD_STATES: string[] = [\n"
for j in range(0, len(states), 6):
    body += "  " + ", ".join(json.dumps(s) for s in states[j : j + 6]) + ",\n"
body += "]\n\n"
body += f"export const SILHOUETTE_FACEBOX_PATH = {json.dumps(silhouette)}\n\n"
body += f"export const SILHOUETTE_BOUNDS = {json.dumps(bounds)} as const\n"

OUT.write_text(body)
print(f"wrote {OUT} ({len(body)} bytes); pools for {len(pools)} states; bounds {bounds}")
